#!/usr/bin/env node
/**
 * Regenerate the frozen frontmatter fixtures from the pinned upstream checkout.
 *
 * The fixtures make the frontmatter suite independent of whether `submodule/dotnet-skills`
 * is present: it asserts against text captured verbatim from the baseline, while a
 * separate test re-checks that capture against the checkout whenever it exists.
 *
 * Usage: node tools/capture-fixtures.mjs [--check]
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { normalizeText, parseDocument, readRequiredKeys, SKILL_NAME_PATTERN } from '../lib/frontmatter.js';
import { checkoutRoot, descriptionForm, repoRoot } from '../test/helpers.mjs';
import { readdirSync } from 'node:fs';

const fixturePath = join(repoRoot, 'test', 'fixtures', 'upstream-descriptions.json');

export function collect() {
  const pluginsRoot = join(checkoutRoot, 'plugins');
  /** @type {object[]} */
  const skills = [];
  for (const plugin of readdirSync(pluginsRoot, { withFileTypes: true })) {
    if (!plugin.isDirectory()) continue;
    const skillsDir = join(pluginsRoot, plugin.name, 'skills');
    let entries;
    try {
      entries = readdirSync(skillsDir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
      if (!entry.isDirectory()) continue;
      const source = readFileSync(join(skillsDir, entry.name, 'SKILL.md'), 'utf8');
      const { frontmatter } = parseDocument(source);
      const required = readRequiredKeys(frontmatter);
      if (!required.ok) throw new Error(`${plugin.name}/${entry.name}: ${required.reason}`);
      if (!SKILL_NAME_PATTERN.test(entry.name)) throw new Error(`${entry.name} is not a valid skill name`);
      skills.push({
        key: `${plugin.name}/${entry.name}`,
        form: descriptionForm(source),
        description: required.description,
        chars: required.description.length,
        sha256: createHash('sha256').update(required.description).digest('hex'),
        userInvocable: required.userInvocable,
        hasUseFor: containsTag(required.description, 'USE FOR:'),
        hasDoNotUseFor: containsTag(required.description, 'DO NOT USE FOR:'),
        hasInvokes: required.description.includes('INVOKES:'),
        rawScalarLength: rawScalarLength(source),
      });
    }
  }
  return skills;
}

/**
 * Whether the exact label text appears.
 *
 * `USE FOR:` is a literal substring of `DO NOT USE FOR:`, and invariant ④ asks only
 * whether the text is present — which is why a skill that forbids a case can still be
 * read as "carrying" the positive label. §7.5's "if and only if" is a constraint on
 * copy-editing, not a claim that the two labels are mutually exclusive upstream.
 */
function containsTag(description, label) {
  return description.includes(label);
}

/**
 * Length of the raw scalar text as it appears upstream, before folding or quote removal.
 *
 * Recorded so the suite can prove the two transformations that move `sourceChars`:
 * folding collapses whitespace, and stripping quotes removes exactly two characters.
 */
function rawScalarLength(source) {
  const lines = source.split('\n');
  const start = lines.findIndex((line) => line.startsWith('description:'));
  if (start < 0) return 0;
  const inline = lines[start].slice('description:'.length).trim();
  if (inline !== '>' && inline !== '>-' && inline !== '') return inline.length;
  let length = 0;
  for (let index = start + 1; index < lines.length; index += 1) {
    const line = lines[index];
    if (line.trim() !== '' && line.trimStart() === line) break;
    length += (length === 0 ? 0 : 1) + line.trim().length;
  }
  return length;
}

function main(argv) {
  const skills = collect();
  const body = `${JSON.stringify(
    {
      note: 'Generated by tools/capture-fixtures.mjs from submodule/dotnet-skills. Do not edit by hand.',
      source: 'dotnet/skills v1.0.0 (cb7c10bd32b250459632df9e6fa1350cdaf00b18)',
      skills,
    },
    null,
    2,
  )}\n`;

  if (argv.includes('--check')) {
    const existing = readFileSync(fixturePath, 'utf8');
    if (existing !== body) {
      process.stderr.write('fixtures are stale: re-run node tools/capture-fixtures.mjs\n');
      return 1;
    }
    process.stdout.write(`fixtures match the checkout (${skills.length} skills)\n`);
    return 0;
  }

  writeFileSync(fixturePath, body, 'utf8');
  const included = skills.filter((skill) => !skill.key.startsWith('dotnet-experimental/'));
  const total = included.reduce((sum, skill) => sum + skill.chars, 0);
  process.stdout.write(
    `captured ${skills.length} skills (${included.length} in range, ${total} description chars) to ` +
      `${fileURLToPath(new URL('../test/fixtures/upstream-descriptions.json', import.meta.url))}\n`,
  );
  process.stdout.write(`normalisation spot check: ${normalizeText('  a\n b ') === 'a b' ? 'ok' : 'FAILED'}\n`);
  return 0;
}

process.exitCode = main(process.argv.slice(2));
